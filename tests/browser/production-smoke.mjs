import {launchBrowser, DEV_URL, PREVIEW_URL} from './helpers.mjs'
import assert from 'node:assert/strict'
const browser = await launchBrowser()
try {
const page=await browser.newPage({viewport:{width:1440,height:900}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
await page.addInitScript(()=>{delete window.showOpenFilePicker})
await page.goto(PREVIEW_URL)
await page.locator('.coordinate-jump').waitFor({timeout:60000})
await page.getByRole('textbox',{name:'X',exact:true}).click()
await page.getByRole('textbox',{name:'X',exact:true}).fill('-12345')
await page.getByRole('textbox',{name:'Z',exact:true}).fill('6789')
await page.getByRole('button',{name:'确定',exact:true}).click()
await page.locator('.buttons > .button').first().click()
const chooser=page.waitForEvent('filechooser')
await page.getByText('载入数据包或模组',{exact:true}).click()
await (await chooser).setFiles('tests/fixtures/persistence-fixture.zip')
await page.locator('.datapack-section > summary').click()
await page.getByText('Persistence regression fixture',{exact:true}).waitFor({timeout:60000})
await page.waitForTimeout(1000)
await page.reload()
await page.locator('.coordinate-jump').waitFor({timeout:60000})
await page.getByText('Persistence regression fixture',{exact:true}).waitFor({timeout:60000})
await page.locator('.leaflet-control-zoom-in').click()
await page.waitForTimeout(700)
const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('mc-datapack-map:v1:view')))
assert.equal(saved.x,-12345);assert.equal(saved.z,6789);assert.equal(saved.zoom,-1)
await page.waitForTimeout(2000)
const painted=await page.locator('canvas.leaflet-tile').evaluateAll(canvases=>canvases.some(c=>c.getContext('2d').getImageData(128,128,1,1).data[3]>0))
assert.ok(painted,'production tiles should contain rendered pixels')
await page.screenshot({path:'tests/results/production-smoke.png'})
assert.deepEqual(errors,[])
console.log(JSON.stringify({passed:true,checks:['production render','coordinate input accessible with sidebar open','coordinate and zoom restoration','uploaded ZIP persisted across reload'],errors}))
} finally {await browser.close()}
