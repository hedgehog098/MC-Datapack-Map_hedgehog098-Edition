import {launchBrowser, DEV_URL, PREVIEW_URL} from './helpers.mjs'
import assert from 'node:assert/strict'
import {writeFile} from 'node:fs/promises'
const browser = await launchBrowser()
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}})
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto(DEV_URL)
 await page.locator('.coordinate-jump').waitFor({timeout:60000})
 const state=fn=>page.locator('#map').evaluate((el,code)=>new Function('s',`return (${code})(s)`)(el.__vueParentComponent.setupState),fn.toString())
 const waitSearch=()=>page.waitForFunction(()=>!document.querySelector('#map').__vueParentComponent.setupState.routeStore.running,null,{timeout:120000})
 await page.locator('.route-search > summary').click()
 await page.locator('.structure-choices input[value="minecraft:village_plains"]').check()
 await page.locator('.structure-choices input[value="minecraft:village_desert"]').check()
 await page.getByRole('textbox',{name:'分组名称',exact:true}).fill('村庄旅行')
 await page.getByRole('button',{name:'保存 / 更新组',exact:true}).click()
 assert.equal(await state(s=>s.routeStore.limit),50)
 assert.equal(await state(s=>s.routeStore.radius),70000)
 const runs=[]
 for(let i=0;i<3;i++) {
  await page.getByRole('button',{name:'开始搜索并规划路线',exact:true}).click()
  await waitSearch()
  const run=await state(s=>({status:s.routeStore.status,error:s.routeStore.error,origin:s.routeStore.origin,stops:s.routeStore.results.map(p=>({...p})),memories:s.routeStore.memories.length,distance:s.routeStore.totalDistance,checked:s.routeStore.checked}))
  assert.equal(run.error,'');assert.equal(run.status,'limit');assert.equal(run.stops.length,50)
  assert.ok(run.stops.every(p=>Math.hypot(p.x-run.origin.x,p.z-run.origin.z)<=70000))
  const keys=new Set(run.stops.map(p=>`${p.id}:${p.x}:${p.z}`))
  for(const old of runs.slice(-2)) assert.ok(old.stops.every(p=>!keys.has(`${p.id}:${p.x}:${p.z}`)),'recent memory repeated')
  assert.equal(run.memories,Math.min(i+1,2))
  runs.push(run);console.log('run',i+1,run.status,run.stops.length,run.checked)
 }
 await page.getByRole('button',{name:'在地图上定位第 1',exact:true}).click()
 const first=runs.at(-1).stops[0]
 assert.deepEqual(await state(s=>({x:s.map.getCenter().lng,z:-s.map.getCenter().lat})),{x:first.x,z:first.z})
 await page.reload()
 await page.locator('.coordinate-jump').waitFor({timeout:60000})
 assert.equal(await state(s=>s.routeStore.memories.length),2)
 assert.equal(await state(s=>s.routeStore.groups[0].name),'村庄旅行')
 assert.equal(await state(s=>s.routeStore.selected.length),2)
 // Hidden grades reflect the selected structure types, not unsupported or unselected ones.
 await state(s=>{s.searchStore.structures.clear();for(const [id,level] of [['minecraft:village_plains','low'],['minecraft:village_desert','medium'],['minecraft:igloo','high']]){s.searchStore.structures.add(id);s.searchStore.priorities[id]=level}s.map.setZoom(-4,{animate:false})})
 await page.waitForTimeout(300)
 const hidden=await page.locator('.info.zoom').innerText()
 assert.match(hidden,/低优先级已隐藏/);assert.match(hidden,/中优先级已隐藏/);assert.doesNotMatch(hidden,/高优先级已隐藏/)
 await state(s=>{s.searchStore.priorities['minecraft:village_plains']='high';s.updateMarkers()})
 assert.equal(await state(s=>s.markerLoading),true)
 await page.locator('.marker-loading').waitFor()
 await page.waitForFunction(()=>!document.querySelector('#map').__vueParentComponent.setupState.markerLoading,null,{timeout:60000})
 assert.equal(await state(s=>s.markerCompleted),await state(s=>s.markerTotal))
 // Stop on an intentionally large search; don't keep scanning in the background.
 await state(s=>{s.routeStore.limit=500;s.routeStore.radius=1000000;s.routeStore.minDistance=10000;void s.routeStore.start()})
 await page.waitForTimeout(100)
 await state(s=>{s.routeStore.stop()})
 await waitSearch()
 assert.equal(await state(s=>s.routeStore.status),'cancelled')
 // A world change invalidates a running search and cannot save results to a new world.
 const memoriesBefore=await state(s=>JSON.stringify(s.routeStore.memories))
 await state(s=>{void s.routeStore.start()})
 await page.waitForTimeout(50)
 await state(s=>{s.settingsStore.seed=12345n})
 await waitSearch()
 assert.equal(await state(s=>s.routeStore.results.length),0)
 assert.equal(await state(s=>JSON.stringify(s.routeStore.memories)),memoriesBefore)
 await page.waitForTimeout(1000)
 assert.equal(await state(s=>s.routeStore.rememberedCount),0)
 assert.deepEqual(errors,[])
 await page.locator('.route-search > summary').click()
 await page.screenshot({path:'tests/results/route-browser.png'})
 await writeFile('tests/results/route-browser-results.json',JSON.stringify({passed:true,runs:runs.map(({stops,...r})=>({...r,count:stops.length})),checks:['default 50 stops / 70k radius','multi-type group save and restore','two-memory dedup across three searches','route coordinate jump','low and medium hidden notices','marker calculation progress','stop and keep partial results','world change cancellation'],errors},null,2))
 console.log('PASS route and map progress browser regression')
} finally {await browser.close()}
