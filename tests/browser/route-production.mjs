import {launchBrowser, DEV_URL, PREVIEW_URL} from './helpers.mjs'
import assert from 'node:assert/strict'
const browser = await launchBrowser()
try {
 const context=await browser.newContext({viewport:{width:1440,height:1000},permissions:['clipboard-read','clipboard-write']})
 const page=await context.newPage(), errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.goto(PREVIEW_URL)
 await page.locator('.coordinate-jump').waitFor({timeout:60000})
 await page.locator('.route-search > summary').click()
 await page.locator('.structure-choices input[value="minecraft:village_plains"]').check()
 await page.getByRole('textbox',{name:'分组名称',exact:true}).fill('远行村庄')
 await page.getByRole('button',{name:'保存 / 更新组',exact:true}).click()
 await page.getByRole('spinbutton',{name:'结果上限（1–500）',exact:true}).fill('3')
 await page.getByRole('button',{name:'开始搜索并规划路线',exact:true}).click()
 await page.waitForFunction(()=>document.querySelectorAll('.route-results li').length===3,null,{timeout:60000})
 const firstRun=await page.locator('.route-results li').allTextContents()
 await page.getByRole('button',{name:'复制 X/Z 路线列表',exact:true}).click()
 const copied=await page.evaluate(()=>navigator.clipboard.readText())
 assert.equal(copied.split('\n').length,4)
 assert.match(copied,/minecraft:village_plains/)
 const positionText=await page.getByRole('button',{name:'在地图上定位第 1',exact:true}).innerText()
 const [,x,z]=positionText.match(/X (-?\d+) · Z (-?\d+)/)
 await page.getByRole('button',{name:'在地图上定位第 1',exact:true}).click()
 const view=await page.evaluate(()=>JSON.parse(localStorage.getItem('mc-datapack-map:v1:view')))
 assert.equal(view.x,Number(x));assert.equal(view.z,Number(z))
 await page.reload()
 await page.locator('.coordinate-jump').waitFor({timeout:60000})
 await page.locator('.route-search > summary').click()
 assert.equal(await page.getByRole('spinbutton',{name:'结果上限（1–500）',exact:true}).inputValue(),'3')
 await page.locator('.memories > summary').click()
 await page.getByRole('button',{name:'查看这次路线',exact:true}).click()
 assert.deepEqual(await page.locator('.route-results li').allTextContents(),firstRun)
 await page.getByRole('button',{name:'开始搜索并规划路线',exact:true}).click()
 await page.waitForFunction(()=>document.querySelectorAll('.route-results li').length===3,null,{timeout:60000})
 const nextRun=await page.locator('.route-results li').allTextContents()
 assert.ok(nextRun.every(row=>!firstRun.includes(row)))
 assert.equal(await page.locator('.memory').count(),2)
 await page.locator('.route-results').scrollIntoViewIfNeeded()
 await page.screenshot({path:'tests/results/route-production.png'})
 assert.deepEqual(errors,[])
 console.log(JSON.stringify({passed:true,checks:['production UI search','saved group and parameters','TSP coordinate list clipboard','map location','reload memory restore','second search excludes first','two memory entries'],errors}))
} finally {await browser.close()}
