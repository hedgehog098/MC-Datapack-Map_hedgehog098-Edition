import {launchBrowser, DEV_URL, PREVIEW_URL} from './helpers.mjs'
import assert from 'node:assert/strict'
const browser = await launchBrowser()
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}}), errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.goto(PREVIEW_URL)
 await page.locator('.coordinate-jump').waitFor({timeout:60000})
 assert.equal(await page.locator('.datapack-section').evaluate(el=>el.open),false)
 assert.equal(await page.locator('.sidebar a[href^="http"]').count(),0)
 assert.equal(await page.locator('.leaflet-control-attribution').count(),0)
 assert.equal(await page.locator('script[src*="beamanalytics"]').count(),0)
 const sidebar=await page.locator('.sidebar').boundingBox(), map=await page.locator('#map').boundingBox()
 assert.ok(map.x>=sidebar.width-1)
 await page.locator('.datapack-section > summary').click()
 await page.locator('.datapack-section .datapack').first().waitFor()
 await page.reload()
 await page.locator('.coordinate-jump').waitFor({timeout:60000})
 assert.equal(await page.locator('.datapack-section').evaluate(el=>el.open),true)
 await page.locator('.datapack-section > summary').click()
 await page.locator('.sidebar-toggle').click()
 await page.waitForTimeout(250)
 assert.equal(Math.round((await page.locator('#map').boundingBox()).width),1440)
 await page.locator('.sidebar-toggle').click()
 await page.waitForTimeout(250)
 assert.equal(await page.locator('.datapack-section').evaluate(el=>el.open),false)
 await page.getByRole('textbox',{name:'X',exact:true}).fill('267')
 await page.getByRole('textbox',{name:'Z',exact:true}).fill('-939')
 await page.getByRole('button',{name:'确定',exact:true}).click()
 const view=await page.evaluate(()=>JSON.parse(localStorage.getItem('mc-datapack-map:v1:view')))
 assert.equal(view.x,267);assert.equal(view.z,-939)
 await page.waitForTimeout(1800)
 await page.screenshot({path:'tests/results/ui-desktop.png'})
 await page.locator('.route-search > summary').click()
 await page.locator('.structure-choices input[value="minecraft:village_plains"]').check()
 await page.getByRole('spinbutton',{name:'结果上限（1–500）',exact:true}).fill('3')
 await page.getByRole('button',{name:'开始搜索并规划路线',exact:true}).click()
 await page.waitForFunction(()=>document.querySelectorAll('.route-results li').length===3,null,{timeout:60000})
 await page.locator('.route-results').scrollIntoViewIfNeeded()
 await page.screenshot({path:'tests/results/ui-route.png'})
 const mobile=await browser.newPage({viewport:{width:390,height:844}})
 mobile.on('pageerror',e=>errors.push(e.message))
 await mobile.goto(PREVIEW_URL)
 await mobile.locator('.coordinate-jump').waitFor({timeout:60000})
 assert.equal(await mobile.locator('.sidebar').isVisible(),false)
 const form=await mobile.locator('.coordinate-jump').boundingBox()
 assert.ok(form.x>=0&&form.x+form.width<=390)
 await mobile.locator('.sidebar-toggle').click()
 assert.equal(await mobile.locator('.sidebar').isVisible(),true)
 await mobile.locator('.datapack-section > summary').click()
 await mobile.locator('.datapack-section .datapack').first().waitFor()
 await mobile.screenshot({path:'tests/results/ui-mobile.png'})
 assert.deepEqual(errors,[])
 console.log('PASS: desktop/mobile layout, collapsible persistent packs, sidebar resize, clean UI, coordinate jump, structure search')
} finally {await browser.close()}
